test("the story graph is internally consistent", () => {
  const report = validateStory(story);
  assert.deepEqual(report.errors, []);
  assert.ok(report.nodes >= 200);
  assert.ok(report.decisions >= 60);
  assert.equal(report.endings, 14);
  assert.ok(report.chapters >= 8 && report.chapters <= 12);
});

test("representative routes reach the ending they name", () => {
  for (const route of routes) {
    const discoveries = route.discoveries ?? emptyDiscoveries();
    const run = walk(story, route.choices, discoveries);
    assert.equal(run.endingId, route.ending, route.ending);
  }
});

test("a first morning cannot use a recognition it has not earned", () => {
  const again = routes.find((route) => route.ending === "ending-again");
  assert.ok(again);
  let run = startRun(story);
  assert.throws(() => {
    for (const choiceId of again.choices) run = choose(story, run, choiceId, emptyDiscoveries());
  });
  const withMemory = walk(story, again.choices, again.discoveries ?? emptyDiscoveries());
  assert.equal(withMemory.endingId, "ending-again");
});

test("the hidden margin stays shut until other mornings exist", () => {
  const margin = routes.find((route) => route.ending === "ending-margin");
  assert.ok(margin?.discoveries);
  assert.ok(margin.discoveries.endings.length >= 3);
  assert.throws(() => walk(story, margin.choices, emptyDiscoveries()));
  assert.equal(walk(story, margin.choices, margin.discoveries).endingId, "ending-margin");
});

test("restoring a checkpoint drops decisions made after it", () => {
  let run = startRun(story);
  const opening = run.checkpoints[0]?.nodeId;
  assert.equal(opening, story.start);
  run = choose(story, run, "m-next", emptyDiscoveries());
  run = choose(story, run, "m-dismiss", emptyDiscoveries());
  assert.equal(run.flags.dismissed, true);
  const restored = restoreCheckpoint(run, story.start);
  assert.ok(restored);
  assert.equal(restored.flags.dismissed, undefined);
  assert.deepEqual(restored.history.map((entry) => entry.nodeId), [story.start]);
  assert.equal(restored.endingId, null);
  const branched = branchFromCheckpoint(run.checkpoints, story.start);
  assert.equal(branched?.flags.dismissed, undefined);
});

test("a broken save becomes an empty morning instead of a crash", () => {
  assert.equal(parseSave("{", story).active, null);
  assert.equal(parseSave(JSON.stringify({ version: 2 }), story).active, null);
  const save = emptySave();
  save.preferences.name = "Ada Lovelace the extremely long invented label that should be cut";
  const parsed = parseSave(serializeSave({ ...save, preferences: { ...save.preferences, name: "x".repeat(80) } }), story);
  assert.equal(parsed.preferences.name.length, 40);
  const nodes = storyMap(story);
  assert.equal(nodes.has("m-wake"), true);
});

test("echo choices stay hidden until that person was met before", () => {
  const node = story.nodes.find((item) => item.choices?.some((choice) => choice.id === "s-echo"));
  assert.ok(node);
  const run = startRun(story);
  run.nodeId = node.id;
  const hidden = availableChoices(story, run, emptyDiscoveries()).map((choice) => choice.id);
  const shown = availableChoices(story, run, { endings: [], nodes: [], people: ["marlow"] }).map((choice) => choice.id);
  assert.equal(hidden.includes("s-echo"), false);
  assert.equal(shown.includes("s-echo"), true);
});
